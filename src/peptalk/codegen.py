"""Generate a template's Pydantic answer models and JSON Schemas from its LinkML schema.

A template's answer schema is LinkML (``schema.yaml`` next to ``prompt.txt``). Answer classes carry the annotation
``answer: true`` and usually derive from ``AnswerBase`` in ``peptalk_common``, which supplies the optional payload
keys. Generating writes, next to ``schema.yaml``:

- ``schema.py``: Pydantic models (extra keys allowed; imports only pydantic and the standard library);
- ``<Class>.schema.json``: the JSON Schema of each answer class.

Built-in templates are generated by ``just gen-schema``; a plugin's templates by ``peptalk templates generate
PATH``. Both need LinkML, which is a development dependency (``pip install 'peptalk-llm[linkml]'``); nothing at
runtime imports it. ``peptalk templates check PATH`` reports generated files that are out of date.
"""

from __future__ import annotations

from pathlib import Path

COMMON = Path(__file__).parent / "templates" / "common.yaml"
#: Lets a template schema write ``imports: [peptalk_common]`` wherever it lives.
IMPORTMAP = {"peptalk_common": str(COMMON.with_suffix(""))}


def answer_classes(schema_path: Path | str) -> list[str]:
    """Classes defined in the schema itself with the annotation ``answer: true``, in schema order."""
    from linkml_runtime.utils.schemaview import SchemaView

    view = SchemaView(str(schema_path), importmap=IMPORTMAP)
    own = view.schema.classes or {}
    return [
        name
        for name in own
        if (ann := view.get_class(name).annotations) and "answer" in ann and str(ann["answer"].value).lower() == "true"
    ]


def generate(schema_path: Path | str) -> dict[Path, str]:
    """The generated files for one template schema, by path (nothing is written)."""
    from linkml.generators.jsonschemagen import JsonSchemaGenerator
    from linkml.generators.pydanticgen import PydanticGenerator

    schema_path = Path(schema_path)
    folder = schema_path.parent
    out = {
        folder / "schema.py": PydanticGenerator(
            str(schema_path), metadata_mode=None, extra_fields="allow", importmap=IMPORTMAP
        ).serialize()
    }
    classes = answer_classes(schema_path)
    if not classes:
        raise ValueError(f"{schema_path}: no class has the annotation 'answer: true'")
    for name in classes:
        out[folder / f"{name}.schema.json"] = (
            JsonSchemaGenerator(str(schema_path), top_class=name, include_null=False, importmap=IMPORTMAP).serialize()
            + "\n"
        )
    return out


def write(schema_path: Path | str) -> list[Path]:
    """Generate and write a template's files; returns the paths written."""
    files = generate(schema_path)
    for path, text in files.items():
        path.write_text(text)
    return list(files)


def stale(schema_path: Path | str) -> list[Path]:
    """Generated files that are missing or differ from what the schema generates now."""
    return [p for p, text in generate(schema_path).items() if not p.exists() or p.read_text() != text]
